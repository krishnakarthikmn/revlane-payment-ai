def ensure_app_role():
    """Tenant-scoped sessions switch to this role, so row-level security applies
    even when the connecting user owns the tables or is a superuser."""
    bind = op.get_bind()
    exists = bind.execute(
        sa.text("SELECT 1 FROM pg_roles WHERE rolname = :role"), {"role": APP_ROLE}
    ).scalar()
    if not exists:
        can_create = bind.execute(
            sa.text("SELECT rolsuper OR rolcreaterole FROM pg_roles WHERE rolname = current_user")
        ).scalar()
        if not can_create:
            raise RuntimeError(
                f"The role {APP_ROLE} does not exist and this user may not create it. "
                "Run `make db` first."
            )
        op.execute(f"CREATE ROLE {APP_ROLE} NOLOGIN")
    member = bind.execute(
        sa.text("SELECT pg_has_role(current_user, :role, 'MEMBER')"), {"role": APP_ROLE}
    ).scalar()
    if not member:
        try:
            with bind.begin_nested():
                op.execute(f"GRANT {APP_ROLE} TO CURRENT_USER")
        except sa.exc.DBAPIError as error:
            raise RuntimeError(
                f"This user cannot switch to the role {APP_ROLE}. Run `make db` first."
            ) from error


def secure_tables():
    op.execute(f"GRANT USAGE ON SCHEMA public TO {APP_ROLE}")

    op.execute("ALTER TABLE tenant ENABLE ROW LEVEL SECURITY")
    op.execute(
        f"CREATE POLICY tenant_isolation ON tenant "
        f"USING (id = {CURRENT_TENANT}) WITH CHECK (id = {CURRENT_TENANT})"
    )
    # Tenants are created and removed by the owner, not by application sessions.
    op.execute(f"GRANT SELECT, UPDATE ON tenant TO {APP_ROLE}")

    for table in TENANT_TABLES:
        op.execute(f'ALTER TABLE "{table}" ENABLE ROW LEVEL SECURITY')
        op.execute(
            f'CREATE POLICY tenant_isolation ON "{table}" '
            f"USING (tenant_id = {CURRENT_TENANT}) WITH CHECK (tenant_id = {CURRENT_TENANT})"
        )
        rights = (
            "SELECT, INSERT" if table in APPEND_ONLY_TABLES else "SELECT, INSERT, UPDATE, DELETE"
        )
        op.execute(f'GRANT {rights} ON "{table}" TO {APP_ROLE}')


